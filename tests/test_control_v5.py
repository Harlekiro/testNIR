"""Этап 4: контрольные числа правил v5 (ТЗ, раздел 9) на трёх наборах. Допуск к ориентирам автора — ±2 %.

Ориентиры раздела 9 посчитаны пробным ноутбуком `reference/метод_v5_пробный.ipynb`. Пакет отличается от него
в двух местах (ТЗ 3.1 и буквальное прочтение правила), поэтому кроме допуска ±2 % тест фиксирует точные числа пакета:
  1) здание с несколькими социальными типами без школы — норма по 4.4.3 (тип, точек которого больше; при равенстве —
     большая норма); пробный ноутбук брал норму первого объекта. Гатчина: −7,8 рабочего места; Петербург: −112;
  2) «не меньше 10 вершин» (шаг 3) — вершины без повторённой замыкающей точки; пробный ноутбук считал и её.
     Петербург: 34 сооружения вместо 36 (2 здания с 9 вершинами — на шаге 6, рабочих мест 0 в обоих случаях);
  3) Петербург: типы greenhouse_complex и plant_nursery отнесены к группе П (решение автора 19.11.2026).
Если данных набора нет — тест пропускается.
"""
import os

import pytest

from conftest import ROOT
from mixuse.config import load_config
from mixuse.blocks import load_layers, build_table

# набор → (жителей, нижняя граница А, основная оценка А + Б, кварталов с П) — раздел 9 ТЗ
ORIENTIR = {
    'vysotsk': (1135, 80, 390, 8),
    'gatchina_layers': (91464, 15334, 36638, 14),
    'spb_full': (5382121, 796823, 1738323, 591),
}
# точные числа пакета (см. описание выше)
EXACT = {
    'vysotsk': (1135, 80, 390, 8),
    'gatchina_layers': (91464, 15327, 36630, 14),
    'spb_full': (5382121, 796926, 1738418, 624),
}
# Петербург, разбивка по шагам таблицы 4.4: зданий, поэтажная площадь (м²), рабочих мест
SPB_STEPS = {
    '1 (сервисы К, ОД, П)': '3324 / 23288124 / 616958',
    '2 (социальные объекты)': '2182 / 5681936 / 149439',
    '3 (сооружения в производственных зонах)': '34 / 15093 / 0',
    '4 (производственная зона, от 2 этажей)': '2310 / 24880461 / 360586',
    '5 (производственная зона, одноэтажные от порога площади)': '2320 / 7855267 / 96979',
    '6 (производственная зона, одноэтажные меньше порога)': '5323 / 2572308 / 0',
    '7 (общественно-деловая зона)': '8285 / 24196348 / 483927',
    '8 (прочее)': '17656 / 33020108 / 0',
    'встроенные помещения': '5311 / 1063075 / 30529',
}


@pytest.fixture(scope='module', params=list(ORIENTIR))
def city(request):
    code = request.param
    cfg = load_config(os.path.join(ROOT, 'configs', f'{code}.yaml'))
    if not os.path.exists(cfg['blocks']):
        pytest.skip(f'нет данных набора {code}')
    L = load_layers(cfg, cfg['_groups'])
    return code, build_table(L, cfg, cfg['params'], cfg['_groups'])


def numbers(city):
    r = city['report']
    return (r['жителей'], r['рабочих мест: нижняя граница (только А)'], r['рабочих мест: основная оценка (А + Б)'],
            int(city['table']['есть_П'].sum()))


def test_within_2_percent_of_orientir(city):
    code, c = city
    got, ref = numbers(c), ORIENTIR[code]
    assert got[0] == ref[0]                                  # жители — без допуска
    for g, r in zip(got[1:3], ref[1:3]):
        assert abs(g - r) <= 0.02 * r, (code, got, ref)


def test_exact_numbers(city):
    code, c = city
    if code in EXACT:
        assert numbers(c) == EXACT[code]


def test_spb_steps(city):
    code, c = city
    if code != 'spb_full':
        pytest.skip('только spb_full')
    assert c['report']['шаги таблицы 4.4: зданий / поэтажная площадь, м² / рабочих мест'] == SPB_STEPS
    assert c['report']['типов без нормы (принята норма группы a_g, 4.4.3)'] == 12     # теплицы и питомники → a_П = 69
