"""Сообщения пользователю об ошибках (ТЗ 18.3): «что не так и как исправить», без текста исключений Python.

Ошибки пакета (неверная анкета или настройки, ошибка в данных, КИТ не задан, нет blocksnet) наследуют UserMessage.
В Jupyter такое исключение печатается одной строкой «✕ …» вместо трассировки (IPython вызывает
_render_traceback_); выполнение ячеек (Run All) при этом останавливается, как при любой ошибке.
В командной строке те же ошибки печатает mixuse.cli — тоже без трассировки.
"""


class UserMessage:
    def _render_traceback_(self):
        return ['✕ ' + str(self), '', 'Расчёт остановлен. Исправьте анкету в шаге 0 или слои и запустите снова.']
